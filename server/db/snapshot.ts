// Writes server/db/catalogSnapshot.ts from the local problem catalog so hosted copies start with problems.
// Only public problem metadata is copied; the database is opened read-only and no user data is read.
import 'dotenv/config';
import Database from 'better-sqlite3';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { CatalogRow } from './catalog.js';

const source = new Database(resolve(process.env.DATABASE_PATH || './data/rickyleet.sqlite'), { readonly: true, fileMustExist: true });
const rows = (source.prepare('SELECT id,slug,title,difficulty,acceptance,tags,paid,likes,dislikes,rating FROM problems ORDER BY CAST(id AS INTEGER), slug').all() as any[]).map(p => [p.id, p.slug, p.title, p.difficulty, p.acceptance, JSON.parse(p.tags), !!p.paid, p.likes, p.dislikes, ...(p.rating ? [p.rating] : [])] as CatalogRow);
source.close();
if (!rows.length) throw new Error('The local catalog is empty. Refresh the catalog in Settings first.');
const out = resolve(import.meta.dirname, 'catalogSnapshot.ts');
writeFileSync(out, `// Generated by \`npm run catalog:snapshot\`. Public LeetCode problem metadata only.\nimport type { CatalogRow } from './catalog.js';\nexport const catalogSnapshot: CatalogRow[] = [\n${rows.map(row => JSON.stringify(row)).join(',\n')},\n];\n`);
console.log(`Wrote ${rows.length} problems to ${out}.`);
